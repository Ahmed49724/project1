/* Quiz questions */
function shuffle<T>(a: T[]): T[] {
  const b = [...a]; for (let i=b.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[b[i],b[j]]=[b[j],b[i]];} return b;
}

export function generateQuiz(count = 10) {
  const qs: { type: string; prompt: string; promptEn: string; options: string[]; correct: number; icon: string }[] = [];
  const verbs = shuffle(VERB_CONJUGATIONS);
  for (let i = 0; i < Math.min(count, verbs.length); i++) {
    const v = verbs[i];
    const distractors = shuffle(VERB_CONJUGATIONS.filter(x => x.ar !== v.ar)).slice(0,3);
    const opts = shuffle([v.ar, ...distractors.map(d=>d.ar)]);
    qs.push({ type:"match", prompt:`ما الفعل المناسب؟ ${v.icon}`, promptEn:`Which verb matches? ${v.icon}`, options:opts, correct:opts.indexOf(v.ar), icon:v.icon });
  }
  return qs;
}
